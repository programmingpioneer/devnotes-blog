const TOPIC_ICONS: Record<string, (props: IconProps) => React.JSX.Element> = {
  frontend: IconFrontend,
  backend: IconBackend,
  devops: IconDevOps,
  ai: IconAI,
};

export function getTopicIcon(
  slug: string
): (props: IconProps) => React.JSX.Element {
  return TOPIC_ICONS[slug] ?? IconFallback;
}